export const spellColor = (spell: {
  color?: string;
  damageType?: string;
  damageComponents?: { type: string }[];
}): string | undefined =>
  spell.color ?? DAMAGE_COLORS[spell.damageComponents?.[0]?.type || spell.damageType || ''];
