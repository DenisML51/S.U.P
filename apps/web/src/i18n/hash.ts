/**
 * The key a Russian text is looked up by in a compiled dictionary: a 53-bit hash (cyrb53) in base 36.
 * The build hashes the dictionary's Russian side with it, so the English chunk carries no Russian.
 */
export function textKey(text: string): string {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < text.length; i++) {
    const ch = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36);
}

/** A key with `{0}`, `{1}`… is a template: the rest of a text around values that change. */
export const isTemplate = (key: string): boolean => /\{\d+\}/.test(key);
